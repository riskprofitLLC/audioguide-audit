import 'package:flutter/foundation.dart';

/// Глобальное состояние плавающих оверлеев.
///
/// Мини-плеер живёт в `MaterialApp.builder` — НАД Navigator'ом,
/// поэтому он рисуется и поверх модальных шторок. Чтобы пилюля
/// не дублировала плеер открытой шторки POI, счётчик
/// [modalSheetOpenCount] инкрементируют все обёртки
/// `showModalBottomSheet` (map_taps, дерево навигации, легенда).
final ValueNotifier<int> modalSheetOpenCount = ValueNotifier<int>(0);

/// Видимость мини-плеера (трек играет, пользователь не на
/// странице своего POI, модальных шторок нет).
///
/// Контролы карты слушают нотификатор и поднимаются над пилюлей
/// (A2c): без него зум/GPS и карточка навигации перекрывались.
final ValueNotifier<bool> miniPlayerVisible = ValueNotifier<bool>(false);

/// Счётчик повторных тапов по уже активной вкладке «Поиск»
/// (P0-1, 6-й проход). Шелл инкрементирует его, когда вкладка
/// «Поиск» уже подсвечена: адрес /map?search=1 при закрытой
/// шторке не пересобирает страницу, и обычный переход ничего
/// бы не сделал. MapPage слушает счётчик и открывает шторку
/// заново.
final ValueNotifier<int> searchSheetRequest = ValueNotifier<int>(0);
