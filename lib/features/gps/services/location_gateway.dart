import '../models/user_position.dart';

/// Статус разрешения на геолокацию.
///
/// Раньше `ensurePermission` возвращал bool и терял причину:
/// при `deniedForever` или выключенной службе пользователь
/// видел «Нет доступа к геолокации» без единого выхода (P1-1,
/// 7-й проход).
enum LocationPermissionStatus {
  /// Доступ есть — можно подписываться на поток позиций.
  granted,

  /// Запрос отклонён (спросить снова можно).
  denied,

  /// Отклонено навсегда — выход только через настройки системы.
  deniedForever,

  /// Служба геолокации выключена на устройстве.
  serviceOff,

  /// Не удалось проверить (таймаут/сбой метод-канала), A11 18-го
  /// прохода.
  ///
  /// НЕ «отказ»: раньше зависший канал молча превращался в denied —
  /// карта показывала плашку «Включить геолокацию» у человека с
  /// выданными правами. Потребители обязаны трактовать это как
  /// «ничего не менять»: без плашек и без остановки трекинга.
  unknown,
}

/// Результат разового определения позиции (A5, 17-й проход).
///
/// Раньше `currentPosition` возвращал `UserPosition?`: таймаут,
/// запрет доступа и выключенная служба выглядели одинаково —
/// UI показывал один текст «Не удалось определить позицию».
/// Теперь UI различает причины и подсказывает, что делать.
sealed class LocateResult {
  const LocateResult();
}

/// Позиция определена.
class LocatePosition extends LocateResult {
  const LocatePosition(this.position);

  final UserPosition position;
}

/// GPS не ответил за отведённое время — слабый сигнал, помещение.
class LocateTimeout extends LocateResult {
  const LocateTimeout();
}

/// Доступ к геолокации не выдан.
class LocatePermissionDenied extends LocateResult {
  const LocatePermissionDenied();
}

/// Служба геолокации выключена на устройстве.
class LocateServiceOff extends LocateResult {
  const LocateServiceOff();
}

/// Позиция недоступна по иной причине (ошибка платформы).
class LocateUnavailable extends LocateResult {
  const LocateUnavailable();
}

/// Абстракция источника геоданных.
///
/// Реализация может быть платформенной (geolocator)
/// или фейковой (тесты, web-демо без реального GPS).
abstract class LocationGateway {

  /// Проверяет разрешение, НЕ задавая системных вопросов.
  ///
  /// Мягкий запрос (P1-1, 7-й проход): карта при открытии больше
  /// не выбрасывает мгновенный системный диалог — вместо него
  /// на карте появляется плашка «Включить геолокацию».
  Future<LocationPermissionStatus> checkPermission();


  /// Запрашивает разрешение (системный диалог) и возвращает
  /// итоговый статус.
  Future<LocationPermissionStatus> ensurePermission();


  /// Поток обновлений позиции пользователя.
  Stream<UserPosition> get positions;


  /// Однократное определение текущей позиции с типизированным
  /// результатом (A5, 17-й проход).
  Future<LocateResult> currentPosition();


  /// Включена ли на устройстве ТОЛЬКО ПРИБЛИЗИТЕЛЬНАЯ геолокация
  /// (A13, 17-й проход).
  ///
  /// Android 12+/iOS 14+ позволяют выдать «примерное» разрешение
  /// (точность 1–3 км) — автогид при этом молчит, а пользователь
  /// не понимает почему. Возвращает `true` — приблизительная,
  /// `false` — точная, `null` — платформа не различает (web,
  /// старые Android) — подсказку не показываем.
  Future<bool?> isLocationAccuracyReduced() async => null;


  /// Последняя известная позиция ПЛАТФОРМЫ (B1, 18-й проход):
  /// датчик ОС хранит последний фикс даже без активной подписки.
  ///
  /// Показывается приглушённым маркером до первого живого фикса:
  /// стоящий пользователь видит точку сразу, а не после
  /// `distanceFilter` (10 м) или таймаута сигнала. `null` —
  /// платформа не хранит/не отдаёт (web).
  Future<UserPosition?> platformLastKnownPosition() async => null;



  /// Изменения состояния СЛУЖБЫ геолокации (вкл/выкл в шторке
  /// телефона), A7, 17-й проход.
  ///
  /// На native реагируем на выключение без ожидания возврата в
  /// приложение; web не поддерживает поток — пустой стрим.
  Stream<bool> get serviceStatusChanges => const Stream.empty();
}
