/// Порог и форматирование для «ближних» плавающих карточек карты:
/// чип ближайшего POI и карточка навигации по маршруту.
///
/// Без порога в режиме «все регионы» карточки показывались для
/// объектов за сотни километров («Отклонение 120000 м») — рядом с
/// картой всей Турции это шум, а не навигация.
library;

/// Дальше этого радиуса «ближний» объект не показывается (метры).
const double kNearbyDisplayRadiusMeters = 2500;


/// Показывать ли объект с таким расстоянием как «ближний».
bool withinNearbyDisplayRadius(double? distanceMeters) {

  return distanceMeters != null &&
      distanceMeters <= kNearbyDisplayRadiusMeters;
}
