/// Конфигурация растровой подложки OpenStreetMap (A11, 9-й проход).
///
/// Единая точка правды для всех мест, где нужен онлайн-растр:
/// стиль карты (подложка под векторными тайлами региона) и
/// фолбэк-стиль региона без карты. Смена источника тайлов —
/// правка этих констант, а не мест использования.
///
/// Политика OSM (operations.osmfoundation.org/policies/tiles):
/// публичный сервер не для массового использования. На Android
/// maplibre-native уже шлёт идентифицирующий User-Agent (имя
/// пакета + версия, проверено по AAR 13.3.0), на web Referer
/// шлёт браузер — формально требование идентификации выполнено.
///
/// Мобильное приложение — основное (web временный): главный
/// сценарий путеводителя — офлайн, и контекст моря/суши вокруг
/// региона даёт ВЕКТОРНАЯ подложка `content/basemap.pmtiles`
/// (z0–8, в бандле); растр OSM — только онлайн-обогащение
/// «когда есть сеть» и опционален до роста аудитории.
abstract class RasterTiles {
  /// Шаблон URL тайла ({z}/{x}/{y}).
  static const String urlTemplate =
      'https://tile.openstreetmap.org/{z}/{x}/{y}.png';

  /// Размер растрового тайла, px.
  static const int tileSize = 256;

  /// Максимальный зум растра: выше — рисуют свои векторные тайлы.
  static const int maxZoom = 19;
}
