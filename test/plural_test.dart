// Склонение существительных после числительных
// («1 место», «2 места», «5 мест», «11 мест», «21 место»).

import 'package:flutter_test/flutter_test.dart';

import 'package:island_guide/core/utils/plural.dart';

void main() {
  test('pluralRu: место/места/мест', () {
    expect(pluralRu(1, 'место', 'места', 'мест'), 'место');
    expect(pluralRu(2, 'место', 'места', 'мест'), 'места');
    expect(pluralRu(4, 'место', 'места', 'мест'), 'места');
    expect(pluralRu(5, 'место', 'места', 'мест'), 'мест');
    expect(pluralRu(11, 'место', 'места', 'мест'), 'мест');
    expect(pluralRu(12, 'место', 'места', 'мест'), 'мест');
    expect(pluralRu(21, 'место', 'места', 'мест'), 'место');
    expect(pluralRu(22, 'место', 'места', 'мест'), 'места');
    expect(pluralRu(25, 'место', 'места', 'мест'), 'мест');
    expect(pluralRu(101, 'место', 'места', 'мест'), 'место');
    expect(pluralRu(111, 'место', 'места', 'мест'), 'мест');
  });

  test('pluralRu: точка/точки/точек', () {
    expect(pluralRu(1, 'точка', 'точки', 'точек'), 'точка');
    expect(pluralRu(3, 'точка', 'точки', 'точек'), 'точки');
    expect(pluralRu(14, 'точка', 'точки', 'точек'), 'точек');
  });

  test('pluralRu: локация/локации/локаций', () {
    expect(pluralRu(1, 'локация', 'локации', 'локаций'), 'локация');
    expect(pluralRu(4, 'локация', 'локации', 'локаций'), 'локации');
    expect(pluralRu(9, 'локация', 'локации', 'локаций'), 'локаций');
  });

  test('pluralRu: маршрут/маршрута/маршрутов', () {
    expect(pluralRu(1, 'маршрут', 'маршрута', 'маршрутов'), 'маршрут');
    expect(pluralRu(2, 'маршрут', 'маршрута', 'маршрутов'), 'маршрута');
    expect(pluralRu(6, 'маршрут', 'маршрута', 'маршрутов'), 'маршрутов');
  });

  test('pluralRu: ноль и отрицательные', () {
    expect(pluralRu(0, 'место', 'места', 'мест'), 'мест');
    expect(pluralRu(-2, 'место', 'места', 'мест'), 'места');
    expect(pluralRu(-11, 'место', 'места', 'мест'), 'мест');
  });
}
